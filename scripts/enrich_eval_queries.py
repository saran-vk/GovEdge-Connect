def enrich():
    with open(EVAL_PATH, "r", encoding="utf-8") as f:
        data = json.load(f)

    for item in data:
        qid = item["id"]
        if qid in TE_ML_TRANSLATIONS:
            item["query_te"] = TE_ML_TRANSLATIONS[qid]["te"]
            item["query_ml"] = TE_ML_TRANSLATIONS[qid]["ml"]

    with open(EVAL_PATH, "w", encoding="utf-8") as f:
        json.dump(data, f, ensure_ascii=False, indent=2)

    print(f"Enriched {len(data)} queries with Telugu and Malayalam in {EVAL_PATH}")

if __name__ == "__main__":
    enrich()
